CREATE OR REPLACE FUNCTION public.accept_follow_request (
  request_id uuid
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  current_user_id uuid := auth.uid();
  request_record public.follow_requests%rowtype;
begin
  if current_user_id is null then
    raise exception 'Authentication required';
  end if;

  select *
  into request_record
  from public.follow_requests
  where id = request_id
    and status = 'pending';

  if not found then
    raise exception 'Follow request not found.';
  end if;

  if request_record.recipient_user_id <> current_user_id then
    raise exception 'Not authorized.';
  end if;

  insert into public.follows (
    follower_id,
    following_id
  )
  values (
    request_record.requester_user_id,
    request_record.recipient_user_id
  )
  on conflict do nothing;

  update public.follow_requests
  set
    status = 'accepted',
    updated_at = now()
  where id = request_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.block_user (
  target_user_id uuid
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Authentication required';
  end if;

  if target_user_id is null then
    raise exception 'Target user is required';
  end if;

  if current_user_id = target_user_id then
    raise exception 'A user cannot block themselves';
  end if;

  insert into public.blocks (
    blocker_id,
    blocked_user_id
  )
  values (
    current_user_id,
    target_user_id
  )
  on conflict do nothing;

  delete from public.follows
  where
    (
      follower_id = current_user_id
      and following_id = target_user_id
    )
    or
    (
      follower_id = target_user_id
      and following_id = current_user_id
    );
end;
$function$;

CREATE OR REPLACE FUNCTION public.can_create_direct_follow (
  target_user_id uuid
)
  RETURNS boolean
  LANGUAGE sql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
  select
    auth.uid() is not null
    and target_user_id is not null
    and target_user_id <> auth.uid()

    -- Direct follows are only allowed for public accounts.
    and exists (
      select 1
      from public.profiles p
      where p.id = target_user_id
        and p.is_public = true
    )

    -- Neither user may have blocked the other.
    and not exists (
      select 1
      from public.blocks b
      where
        (
          b.blocker_id = auth.uid()
          and b.blocked_user_id = target_user_id
        )
        or
        (
          b.blocker_id = target_user_id
          and b.blocked_user_id = auth.uid()
        )
    );
$function$;

CREATE OR REPLACE FUNCTION public.can_create_follow_request (
  target_user_id uuid
)
  RETURNS boolean
  LANGUAGE sql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
  select
    auth.uid() is not null
    and target_user_id is not null
    and target_user_id <> auth.uid()

    -- Follow requests are only for private accounts.
    and exists (
      select 1
      from public.profiles p
      where p.id = target_user_id
        and p.is_public = false
    )

    -- Do not allow a request if the relationship already exists.
    and not exists (
      select 1
      from public.follows f
      where f.follower_id = auth.uid()
        and f.following_id = target_user_id
    )

    -- Neither side may have blocked the other.
    and not exists (
      select 1
      from public.blocks b
      where
        (
          b.blocker_id = auth.uid()
          and b.blocked_user_id = target_user_id
        )
        or
        (
          b.blocker_id = target_user_id
          and b.blocked_user_id = auth.uid()
        )
    );
$function$;

