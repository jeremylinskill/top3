CREATE OR REPLACE FUNCTION public.validate_profile_content()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
begin
  if public.contains_blocked_content(new.display_name) then
    raise exception
      using
        errcode = 'P0001',
        message = 'PROFILE_DISPLAY_NAME_BLOCKED_CONTENT';
  end if;

  if public.contains_blocked_content(new.username) then
    raise exception
      using
        errcode = 'P0001',
        message = 'PROFILE_USERNAME_BLOCKED_CONTENT';
  end if;

  if public.contains_blocked_content(new.bio) then
    raise exception
      using
        errcode = 'P0001',
        message = 'PROFILE_BIO_BLOCKED_CONTENT';
  end if;

  return new;
end;
$function$;

