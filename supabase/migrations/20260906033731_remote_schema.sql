CREATE OR REPLACE FUNCTION public.contains_blocked_content (
  input_text text
)
  RETURNS boolean
  LANGUAGE sql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
  select exists (
    select 1
    from public.content_filter_terms t
    where
      input_text is not null
      and btrim(input_text) <> ''
      and (
        ' ' ||
        lower(
          regexp_replace(
            input_text,
            '[^[:alnum:]_]+',
            ' ',
            'g'
          )
        ) ||
        ' '
      ) like (
        '% ' ||
        lower(
          regexp_replace(
            t.term,
            '[^[:alnum:]_]+',
            ' ',
            'g'
          )
        ) ||
        ' %'
      )
  );
$function$;

