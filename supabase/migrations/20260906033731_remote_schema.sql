CREATE OR REPLACE FUNCTION public.validate_comment_content()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
begin
  if public.contains_blocked_content(new.content) then
    raise exception
      using
