CREATE OR REPLACE FUNCTION public.get_visible_comment_counts (
  collection_ids uuid[]
)
  RETURNS TABLE (
    collection_id uuid,
    comment_count bigint
  )
  LANGUAGE sql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
  select
    c.collection_id,
    count(*) as comment_count
  from public.comments c
  where
    c.collection_id = any(collection_ids)
    and c.removed_at is null
    and exists (
      select 1
      from public.collections col
      where col.id = c.collection_id
        and (
          col.user_id = auth.uid()
          or (
            col.status = 'published'
            and col.published_at is not null
            and col.removed_at is null
            and public.can_view_published_collection(
              col.user_id
            )
          )
        )
    )
    and not exists (
      select 1
      from public.blocks b
      where
        (
          b.blocker_id = auth.uid()
          and b.blocked_user_id = c.user_id
        )
        or
        (
          b.blocker_id = c.user_id
          and b.blocked_user_id = auth.uid()
        )
    )
  group by c.collection_id;
$function$;

CREATE OR REPLACE FUNCTION public.register_push_token (
  p_expo_push_token text,
  p_platform        text
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  current_user_id uuid;
begin
  current_user_id := auth.uid();

  if current_user_id is null then
    raise exception 'Authentication required';
  end if;

  if p_platform not in ('ios', 'android') then
    raise exception 'Invalid push token platform';
  end if;

  delete from public.push_tokens
  where expo_push_token = p_expo_push_token
    and user_id <> current_user_id;

  insert into public.push_tokens (
    user_id,
    expo_push_token,
    platform,
    updated_at
  )
  values (
    current_user_id,
    p_expo_push_token,
    p_platform,
    now()
  )
  on conflict (expo_push_token)
  do update set
    user_id = excluded.user_id,
    platform = excluded.platform,
    updated_at = now();
end;
$function$;

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
  RETURNS event_trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'pg_catalog'
  AS $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.search_visible_profiles (
  search_query text,
  result_limit integer DEFAULT 20
)
  RETURNS TABLE (
    id                       uuid,
    username                 text,
    display_name             text,
    bio                      text,
    avatar_url               text,
    is_public                boolean,
    has_completed_onboarding boolean,
    is_admin                 boolean
  )
  LANGUAGE sql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
  select
    p.id,
    p.username,
    p.display_name,
    p.bio,
    p.avatar_url,
    p.is_public,
    p.has_completed_onboarding,
    p.is_admin
  from public.profiles p
  where
    auth.uid() is not null
    and p.id <> auth.uid()
    and (
      p.username ilike '%' || search_query || '%'
      or p.display_name ilike '%' || search_query || '%'
    )

    -- Hide relationships blocked in either direction.
    and not exists (
      select 1
      from public.blocks b
      where
        (
          b.blocker_id = auth.uid()
          and b.blocked_user_id = p.id
        )
        or
        (
          b.blocker_id = p.id
          and b.blocked_user_id = auth.uid()
        )
    )

  order by p.display_name asc
  limit least(
    greatest(coalesce(result_limit, 20), 1),
    20
  );
$function$;

