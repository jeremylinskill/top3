create table public.collection_options (
  id text primary key,
  slug text not null,
  category_id text not null,
  kind text not null,
  name text not null,
  group_name text,
  browse_label text,
  keywords text[] not null default '{}',
  search_hints text[] not null default '{}',
  featured boolean not null default false,
  trending_enabled boolean not null default false,
  active boolean not null default true,
  display_order integer not null default 0,
  entity_kind text,
  provider_key text,
  provider_mode text,
  provider_config jsonb not null default '{}'::jsonb,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),

  constraint collection_options_id_check
    check (btrim(id) <> ''),

  constraint collection_options_category_check
    check (
      category_id in (
        'albums',
        'artists',
        'books',
        'games',
        'movies',
        'podcasts',
        'songs',
        'tv'
      )
    ),

  constraint collection_options_kind_check
    check (kind in ('type', 'theme')),

  constraint collection_options_name_check
    check (btrim(name) <> ''),

  constraint collection_options_slug_check
    check (btrim(slug) <> ''),

  constraint collection_options_provider_config_check
    check (jsonb_typeof(provider_config) = 'object'),

  constraint collection_options_category_kind_slug_key
    unique (category_id, kind, slug)
);

alter table public.collection_options
  enable row level security;

create index collection_options_active_browse_idx
  on public.collection_options (
    category_id,
    kind,
    active,
    display_order,
    name
  );

create table public.collection_option_suggestions (
  id bigint generated by default as identity primary key,
  option_id text not null
    references public.collection_options(id)
    on delete cascade,
  item_id text not null,
  item jsonb not null,
  display_order integer not null default 0,
  active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),

  constraint collection_option_suggestions_item_id_check
    check (btrim(item_id) <> ''),

  constraint collection_option_suggestions_item_check
    check (
      jsonb_typeof(item) = 'object'
      and coalesce(item ->> 'id', '') = item_id
      and btrim(coalesce(item ->> 'title', '')) <> ''
    ),

  constraint collection_option_suggestions_option_item_key
    unique (option_id, item_id)
);

alter table public.collection_option_suggestions
  enable row level security;

create index collection_option_suggestions_browse_idx
  on public.collection_option_suggestions (
    option_id,
    active,
    display_order,
    id
  );

alter table public.collections
  add column if not exists collection_option_id text;

alter table public.collections
  add constraint collections_collection_option_id_fkey
  foreign key (collection_option_id)
  references public.collection_options(id)
  on delete restrict;

create index collections_collection_option_id_idx
  on public.collections (collection_option_id)
  where collection_option_id is not null;

create unique index collections_unique_option_identity
  on public.collections (
    user_id,
    collection_option_id
  )
  where
    removed_at is null
    and collection_option_id is not null;

create policy "Active collection options are readable"
  on public.collection_options
  for select
  to public
  using (active);

create policy "Active collection option suggestions are readable"
  on public.collection_option_suggestions
  for select
  to public
  using (
    active
    and exists (
      select 1
      from public.collection_options option
      where
        option.id = option_id
        and option.active
    )
  );

grant select
  on table public.collection_options
  to anon, authenticated;

grant select
  on table public.collection_option_suggestions
  to anon, authenticated;

grant all
  on table public.collection_options
  to postgres, service_role;

grant all
  on table public.collection_option_suggestions
  to postgres, service_role;

grant all
  on sequence public.collection_option_suggestions_id_seq
  to postgres, service_role;

