-- Associate existing known Type and Theme collections with stable option IDs.
-- Leave anything that cannot be matched confidently unchanged.

update public.collections
set collection_option_id = case
  when
    lower(btrim(category)) = 'movies'
    and lower(btrim(coalesce(type, ''))) = 'actors'
    and btrim(coalesce(topic, '')) = ''
    then 'movies-type-actors'

  when
    lower(btrim(category)) = 'movies'
    and lower(btrim(coalesce(type, ''))) = 'directors'
    and btrim(coalesce(topic, '')) = ''
    then 'movies-type-directors'

  when lower(btrim(category)) = 'movies' then
    case lower(btrim(coalesce(theme_id, '')))
      when 'comfort-movies'
        then 'movies-theme-comfort-movies'
      when 'never-get-tired-of'
        then 'movies-theme-never-get-tired-of'
      when 'tom-cruise-movies'
        then 'movies-theme-tom-cruise-movies'
      when 'netflix-originals'
        then 'movies-theme-netflix-originals'
      when '1980s-movies'
        then 'movies-theme-1980s-movies'
      when 'movies-that-made-me-cry'
        then 'movies-theme-movies-that-made-me-cry'
      when 'see-again-first-time'
        then 'movies-theme-see-again-first-time'
      else collection_option_id
    end

  else collection_option_id
end
where
  collection_option_id is null
  and lower(btrim(category)) = 'movies'
  and (
    (
      lower(btrim(coalesce(type, ''))) in (
        'actors',
        'directors'
      )
      and btrim(coalesce(topic, '')) = ''
    )
    or lower(btrim(coalesce(theme_id, ''))) in (
      'comfort-movies',
      'never-get-tired-of',
      'tom-cruise-movies',
      'netflix-originals',
      '1980s-movies',
      'movies-that-made-me-cry',
      'see-again-first-time'
    )
  );

